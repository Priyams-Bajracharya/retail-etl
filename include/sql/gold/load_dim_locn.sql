USE SCHEMA retail_etl.gold;
CREATE OR REPLACE TEMPORARY TABLE tmp_dim_locn_src AS
SELECT l.STORE_ID, l.STORE_NM, dd.DISTRICT_KY, l.BUSINESS_DT
FROM retail_etl.silver.SLV_LOCATION l
JOIN retail_etl.gold.DIM_DISTRICT dd ON dd.DISTRICT_ID = l.DISTRICT_ID
WHERE l.BUSINESS_DT = %(business_date)s;

UPDATE retail_etl.gold.DIM_LOCN d
SET CURR_FLG = FALSE, EFF_END_DT = DATEADD(day, -1, s.BUSINESS_DT), UPDATE_TS = CURRENT_TIMESTAMP()
FROM tmp_dim_locn_src s
WHERE d.LOCN_ID = s.STORE_ID AND d.CURR_FLG = TRUE
  AND s.BUSINESS_DT > d.EFF_START_DT
  AND d.DISTRICT_KY IS DISTINCT FROM s.DISTRICT_KY;

INSERT INTO retail_etl.gold.DIM_LOCN (LOCN_ID, LOCN_NM, DISTRICT_KY, CURR_FLG, EFF_START_DT, EFF_END_DT)
SELECT s.STORE_ID, s.STORE_NM, s.DISTRICT_KY, TRUE, s.BUSINESS_DT, DATE '9999-12-31'
FROM tmp_dim_locn_src s
WHERE NOT EXISTS (SELECT 1 FROM retail_etl.gold.DIM_LOCN d
                  WHERE d.LOCN_ID = s.STORE_ID AND d.CURR_FLG = TRUE);

UPDATE retail_etl.gold.DIM_LOCN d
SET LOCN_NM = s.STORE_NM, UPDATE_TS = CURRENT_TIMESTAMP()
FROM tmp_dim_locn_src s
WHERE d.LOCN_ID = s.STORE_ID AND d.LOCN_NM IS DISTINCT FROM s.STORE_NM;