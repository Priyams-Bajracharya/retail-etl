MERGE INTO retail_etl.gold.DIM_MONTH t
USING (
    SELECT TO_NUMBER(TO_CHAR(d, 'YYYYMM')) AS MONTH_KY,
           MIN(MONTH(d)) AS MONTH_NUM,
           MIN(TO_CHAR(d, 'MMMM')) AS MONTH_NM,
           MIN(d) AS S_DT, MAX(d) AS E_DT,
           MIN(YEAR(d)) AS YEAR_KY
    FROM (SELECT DATEADD(day, ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1, DATE '2026-01-01') AS d
          FROM TABLE(GENERATOR(ROWCOUNT => 365)))
    GROUP BY TO_CHAR(d, 'YYYYMM')
) s ON t.MONTH_KY = s.MONTH_KY
WHEN NOT MATCHED THEN INSERT (MONTH_KY, MONTH_ID, MONTH_NUM, MONTH_NM, MONTH_START_DT, MONTH_END_DT, YEAR_KY)
VALUES (s.MONTH_KY, s.MONTH_KY, s.MONTH_NUM, s.MONTH_NM, s.S_DT, s.E_DT, s.YEAR_KY);