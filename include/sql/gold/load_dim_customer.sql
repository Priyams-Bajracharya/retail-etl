MERGE INTO retail_etl.gold.DIM_CUSTOMER t
USING (SELECT -1 AS CUSTOMER_KY, 0 AS CUSTOMER_ID, 'Unknown' AS CUSTOMER_NM, FALSE AS LOYALTY_FLG) s
ON t.CUSTOMER_KY = s.CUSTOMER_KY
WHEN NOT MATCHED THEN INSERT (CUSTOMER_KY, CUSTOMER_ID, CUSTOMER_NM, LOYALTY_FLG)
    VALUES (s.CUSTOMER_KY, s.CUSTOMER_ID, s.CUSTOMER_NM, s.LOYALTY_FLG);

MERGE INTO retail_etl.gold.DIM_CUSTOMER t
USING (SELECT CUSTOMER_ID AS CUSTOMER_KY, CUSTOMER_ID, CUSTOMER_NM, LOYALTY_FLG
       FROM retail_etl.silver.SLV_CUSTOMER
       WHERE BUSINESS_DT = %(business_date)s) s
ON t.CUSTOMER_ID = s.CUSTOMER_ID
WHEN MATCHED AND (t.CUSTOMER_NM IS DISTINCT FROM s.CUSTOMER_NM OR t.LOYALTY_FLG IS DISTINCT FROM s.LOYALTY_FLG)
    THEN UPDATE SET CUSTOMER_NM = s.CUSTOMER_NM, LOYALTY_FLG = s.LOYALTY_FLG, UPDATE_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (CUSTOMER_KY, CUSTOMER_ID, CUSTOMER_NM, LOYALTY_FLG)
    VALUES (s.CUSTOMER_KY, s.CUSTOMER_ID, s.CUSTOMER_NM, s.LOYALTY_FLG);