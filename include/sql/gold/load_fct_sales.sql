USE SCHEMA retail_etl.gold;

DELETE FROM retail_etl.gold.FCT_SALES
WHERE DAY_KY = TO_NUMBER(TO_CHAR(%(business_date)s::DATE, 'YYYYMMDD'));

INSERT INTO retail_etl.gold.FCT_SALES
    (TXN_ID, TXN_LINE_ID, ITEM_KY, LOCN_KY, DAY_KY, CUSTOMER_KY,
     SLS_QTY, UNIT_PRICE_AMT, DISC_AMT, SLS_AMT)
SELECT s.TXN_ID, s.TXN_LINE_ID, i.ITEM_KY, l.LOCN_KY,
       TO_NUMBER(TO_CHAR(s.SALE_DT, 'YYYYMMDD')),
       COALESCE(c.CUSTOMER_KY, -1),
       s.SLS_QTY, s.UNIT_PRICE_AMT, s.DISC_AMT, s.SLS_AMT
FROM retail_etl.silver.SLV_SALES_LINE s
JOIN retail_etl.gold.DIM_ITEM i
  ON i.ITEM_ID = s.ITEM_ID AND s.SALE_DT BETWEEN i.EFF_START_DT AND i.EFF_END_DT
JOIN retail_etl.gold.DIM_LOCN l
  ON l.LOCN_ID = s.STORE_ID AND s.SALE_DT BETWEEN l.EFF_START_DT AND l.EFF_END_DT
LEFT JOIN retail_etl.gold.DIM_CUSTOMER c
  ON c.CUSTOMER_ID = s.CUSTOMER_ID
WHERE s.BUSINESS_DT = %(business_date)s;