MERGE INTO retail_etl.gold.DIM_DAY t
USING (
    SELECT TO_NUMBER(TO_CHAR(d, 'YYYYMMDD')) AS DAY_KY, d AS FULL_DT,
           DAYOFMONTH(d) AS DAY_NUM,
           TO_NUMBER(TO_CHAR(DATEADD(day, -(DAYOFWEEKISO(d) - 1), d), 'YYYYMMDD')) AS WEEK_KY,
           TO_NUMBER(TO_CHAR(d, 'YYYYMM')) AS MONTH_KY
    FROM (SELECT DATEADD(day, ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1, DATE '2026-01-01') AS d
          FROM TABLE(GENERATOR(ROWCOUNT => 365)))
) s ON t.DAY_KY = s.DAY_KY
WHEN NOT MATCHED THEN INSERT (DAY_KY, DAY_ID, FULL_DT, DAY_NUM, WEEK_KY, MONTH_KY)
VALUES (s.DAY_KY, s.DAY_KY, s.FULL_DT, s.DAY_NUM, s.WEEK_KY, s.MONTH_KY);