MERGE INTO retail_etl.gold.DIM_WEEK t
USING (
    SELECT TO_NUMBER(TO_CHAR(wk, 'YYYYMMDD')) AS WEEK_KY,
           MIN(WEEKISO(d)) AS WEEK_NUM,
           wk AS S_DT, DATEADD(day, 6, wk) AS E_DT,
           MIN(YEAROFWEEKISO(d)) AS YEAR_KY
    FROM (SELECT d, DATEADD(day, -(DAYOFWEEKISO(d) - 1), d) AS wk
          FROM (SELECT DATEADD(day, ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1, DATE '2026-01-01') AS d
                FROM TABLE(GENERATOR(ROWCOUNT => 365))))
    GROUP BY wk
) s ON t.WEEK_KY = s.WEEK_KY
WHEN NOT MATCHED THEN INSERT (WEEK_KY, WEEK_ID, WEEK_NUM, WEEK_START_DT, WEEK_END_DT, YEAR_KY)
VALUES (s.WEEK_KY, s.WEEK_KY, s.WEEK_NUM, s.S_DT, s.E_DT, s.YEAR_KY);