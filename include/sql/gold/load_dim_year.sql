MERGE INTO retail_etl.gold.DIM_YEAR t
USING (SELECT 2026 AS YEAR_KY, 2026 AS YEAR_ID,
              DATE '2026-01-01' AS S_DT, DATE '2026-12-31' AS E_DT) s
ON t.YEAR_KY = s.YEAR_KY
WHEN NOT MATCHED THEN INSERT (YEAR_KY, YEAR_ID, YEAR_START_DT, YEAR_END_DT)
VALUES (s.YEAR_KY, s.YEAR_ID, s.S_DT, s.E_DT);