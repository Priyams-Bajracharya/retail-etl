USE SCHEMA retail_etl.gold;
CREATE OR REPLACE TEMPORARY TABLE tmp_dim_item_src AS
SELECT i.ITEM_ID, i.ITEM_NM, i.BRAND_NM, sc.SUBCATG_KY, i.BUSINESS_DT
FROM retail_etl.silver.SLV_ITEM i
JOIN retail_etl.gold.DIM_SUBCATG sc ON sc.SUBCATG_ID = i.SUBCLASS_ID
WHERE i.BUSINESS_DT = %(business_date)s;

UPDATE retail_etl.gold.DIM_ITEM d
SET CURR_FLG = FALSE, EFF_END_DT = DATEADD(day, -1, s.BUSINESS_DT), UPDATE_TS = CURRENT_TIMESTAMP()
FROM tmp_dim_item_src s
WHERE d.ITEM_ID = s.ITEM_ID AND d.CURR_FLG = TRUE
  AND s.BUSINESS_DT > d.EFF_START_DT
  AND (d.BRAND_NM IS DISTINCT FROM s.BRAND_NM OR d.SUBCATG_KY IS DISTINCT FROM s.SUBCATG_KY);

INSERT INTO retail_etl.gold.DIM_ITEM (ITEM_ID, ITEM_NM, BRAND_NM, SUBCATG_KY, CURR_FLG, EFF_START_DT, EFF_END_DT)
SELECT s.ITEM_ID, s.ITEM_NM, s.BRAND_NM, s.SUBCATG_KY, TRUE, s.BUSINESS_DT, DATE '9999-12-31'
FROM tmp_dim_item_src s
WHERE NOT EXISTS (SELECT 1 FROM retail_etl.gold.DIM_ITEM d
                  WHERE d.ITEM_ID = s.ITEM_ID AND d.CURR_FLG = TRUE);

UPDATE retail_etl.gold.DIM_ITEM d
SET ITEM_NM = s.ITEM_NM, UPDATE_TS = CURRENT_TIMESTAMP()
FROM tmp_dim_item_src s
WHERE d.ITEM_ID = s.ITEM_ID AND d.ITEM_NM IS DISTINCT FROM s.ITEM_NM;