MERGE INTO retail_etl.gold.DIM_DISTRICT t
USING (SELECT DISTINCT l.DISTRICT_ID, l.DISTRICT_NM, r.REGN_KY
       FROM retail_etl.silver.SLV_LOCATION l
       JOIN retail_etl.gold.DIM_REGN r ON r.REGN_ID = l.REGION_ID
       WHERE l.BUSINESS_DT = %(business_date)s) s
ON t.DISTRICT_ID = s.DISTRICT_ID
WHEN MATCHED AND (t.DISTRICT_NM IS DISTINCT FROM s.DISTRICT_NM OR t.REGN_KY IS DISTINCT FROM s.REGN_KY)
    THEN UPDATE SET DISTRICT_NM = s.DISTRICT_NM, REGN_KY = s.REGN_KY, UPDATE_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (DISTRICT_ID, DISTRICT_NM, REGN_KY)
    VALUES (s.DISTRICT_ID, s.DISTRICT_NM, s.REGN_KY);