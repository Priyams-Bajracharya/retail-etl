MERGE INTO retail_etl.gold.DIM_SUBCATG t
USING (SELECT DISTINCT i.SUBCLASS_ID AS SUBCATG_ID, i.SUBCLASS_NM AS SUBCATG_NM, c.CATG_KY
       FROM retail_etl.silver.SLV_ITEM i
       JOIN retail_etl.gold.DIM_CATG c ON c.CATG_ID = i.CATEGORY_ID
       WHERE i.BUSINESS_DT = %(business_date)s) s
ON t.SUBCATG_ID = s.SUBCATG_ID
WHEN MATCHED AND (t.SUBCATG_NM IS DISTINCT FROM s.SUBCATG_NM OR t.CATG_KY IS DISTINCT FROM s.CATG_KY)
    THEN UPDATE SET SUBCATG_NM = s.SUBCATG_NM, CATG_KY = s.CATG_KY, UPDATE_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (SUBCATG_ID, SUBCATG_NM, CATG_KY)
    VALUES (s.SUBCATG_ID, s.SUBCATG_NM, s.CATG_KY);