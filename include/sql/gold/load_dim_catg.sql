MERGE INTO retail_etl.gold.DIM_CATG t
USING (SELECT DISTINCT CATEGORY_ID AS CATG_ID, CATEGORY_NM AS CATG_NM
       FROM retail_etl.silver.SLV_ITEM
       WHERE BUSINESS_DT = %(business_date)s) s
ON t.CATG_ID = s.CATG_ID
WHEN MATCHED AND t.CATG_NM IS DISTINCT FROM s.CATG_NM
    THEN UPDATE SET CATG_NM = s.CATG_NM, UPDATE_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (CATG_ID, CATG_NM) VALUES (s.CATG_ID, s.CATG_NM);