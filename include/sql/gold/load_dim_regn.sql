MERGE INTO retail_etl.gold.DIM_REGN t
USING (SELECT DISTINCT REGION_ID AS REGN_ID, REGION_NM AS REGN_NM
       FROM retail_etl.silver.SLV_LOCATION
       WHERE BUSINESS_DT = %(business_date)s) s
ON t.REGN_ID = s.REGN_ID
WHEN MATCHED AND t.REGN_NM IS DISTINCT FROM s.REGN_NM
    THEN UPDATE SET REGN_NM = s.REGN_NM, UPDATE_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (REGN_ID, REGN_NM) VALUES (s.REGN_ID, s.REGN_NM);