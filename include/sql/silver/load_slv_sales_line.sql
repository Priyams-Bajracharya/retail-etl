CREATE OR REPLACE TEMPORARY TABLE silver.TMP_SALES AS
WITH typed AS (
    SELECT b.SRC_FILE_NM, b.SRC_ROW_NUM, b.BUSINESS_DT,
           TRIM(b.TXN_ID) AS TXN_ID,
           TRY_TO_NUMBER(TRIM(b.TXN_LINE_ID)) AS TXN_LINE_ID,
           TRY_TO_DATE(TRIM(b.BUSINESS_DATE)) AS SALE_DT,
           TRY_TO_NUMBER(TRIM(b.STORE_ID)) AS STORE_ID,
           TRY_TO_NUMBER(NULLIF(TRIM(b.CUSTOMER_ID), '')) AS CUSTOMER_ID,
           TRY_TO_NUMBER(NULLIF(TRIM(b.ITEM_ID), '')) AS ITEM_ID,
           TRY_TO_NUMBER(TRIM(b.QUANTITY)) AS SLS_QTY,
           TRY_TO_NUMBER(TRIM(b.UNIT_PRICE), 12, 2) AS UNIT_PRICE_AMT,
           TRY_TO_NUMBER(TRIM(b.DISCOUNT_AMOUNT), 12, 2) AS DISC_AMT,
           TRY_TO_NUMBER(TRIM(b.NET_AMOUNT), 14, 2) AS SLS_AMT,
           CONCAT_WS('|', b.TXN_ID, b.TXN_LINE_ID, b.BUSINESS_DATE, b.STORE_ID, b.CUSTOMER_ID,
                     b.ITEM_ID, b.QUANTITY, b.UNIT_PRICE, b.DISCOUNT_AMOUNT, b.NET_AMOUNT) AS ROW_DATA
    FROM bronze.BRZ_POS_SALES b
    WHERE b.BUSINESS_DT = %(business_date)s
),
ranked AS (
    SELECT t.*,
           ROW_NUMBER() OVER (PARTITION BY t.TXN_ID, t.TXN_LINE_ID ORDER BY t.SRC_ROW_NUM) AS RN,
           i.ITEM_ID AS MASTER_ITEM_ID
    FROM typed t
    LEFT JOIN silver.SLV_ITEM i ON i.ITEM_ID = t.ITEM_ID AND i.BUSINESS_DT = t.BUSINESS_DT
)
SELECT r.*,
       CASE
           WHEN r.ITEM_ID IS NULL THEN 'NULL_ITEM_ID'
           WHEN r.TXN_LINE_ID IS NULL OR r.SALE_DT IS NULL OR r.STORE_ID IS NULL OR r.SLS_QTY IS NULL
                OR r.UNIT_PRICE_AMT IS NULL OR r.DISC_AMT IS NULL OR r.SLS_AMT IS NULL THEN 'BAD_VALUE'
           WHEN r.SLS_QTY < 0 THEN 'NEGATIVE_QTY'
           WHEN r.MASTER_ITEM_ID IS NULL THEN 'ITEM_NOT_IN_MASTER'
           WHEN r.RN > 1 THEN 'DUPLICATE_LINE'
       END AS REASON_CD
FROM ranked r;

DELETE FROM silver.REJ_ROW WHERE BUSINESS_DT = %(business_date)s AND SRC_TABLE = 'BRZ_POS_SALES';

INSERT INTO silver.REJ_ROW (BUSINESS_DT, SRC_TABLE, SRC_FILE_NM, SRC_ROW_NUM, REASON_CD, ROW_DATA)
SELECT BUSINESS_DT, 'BRZ_POS_SALES', SRC_FILE_NM, SRC_ROW_NUM, REASON_CD, ROW_DATA
FROM silver.TMP_SALES WHERE REASON_CD IS NOT NULL;

DELETE FROM silver.SLV_SALES_LINE WHERE BUSINESS_DT = %(business_date)s;

INSERT INTO silver.SLV_SALES_LINE (TXN_ID, TXN_LINE_ID, SALE_DT, STORE_ID, CUSTOMER_ID, ITEM_ID,
                                   SLS_QTY, UNIT_PRICE_AMT, DISC_AMT, SLS_AMT, SRC_ROW_NUM, BUSINESS_DT)
SELECT TXN_ID, TXN_LINE_ID, SALE_DT, STORE_ID, CUSTOMER_ID, ITEM_ID,
       SLS_QTY, UNIT_PRICE_AMT, DISC_AMT, SLS_AMT, SRC_ROW_NUM, BUSINESS_DT
FROM silver.TMP_SALES WHERE REASON_CD IS NULL;