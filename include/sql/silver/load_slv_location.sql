DELETE FROM silver.SLV_LOCATION WHERE BUSINESS_DT = %(business_date)s;

INSERT INTO silver.SLV_LOCATION (STORE_ID, STORE_NM, DISTRICT_ID, DISTRICT_NM, REGION_ID, REGION_NM, OPEN_DT, BUSINESS_DT)
SELECT TRY_TO_NUMBER(TRIM(b.STORE_ID)), TRIM(b.STORE_NAME),
       TRY_TO_NUMBER(TRIM(b.DISTRICT_ID)), TRIM(b.DISTRICT_NAME),
       TRY_TO_NUMBER(TRIM(b.REGION_ID)), TRIM(b.REGION_NAME),
       TRY_TO_DATE(TRIM(b.OPEN_DATE)), b.BUSINESS_DT
FROM bronze.BRZ_STORE_MASTER b
WHERE b.BUSINESS_DT = %(business_date)s AND TRY_TO_NUMBER(TRIM(b.STORE_ID)) IS NOT NULL;