DELETE FROM silver.SLV_ITEM WHERE BUSINESS_DT = %(business_date)s;

INSERT INTO silver.SLV_ITEM (ITEM_ID, ITEM_NM, BRAND_NM, SUBCLASS_ID, SUBCLASS_NM, CATEGORY_ID, CATEGORY_NM, BUSINESS_DT)
SELECT TRY_TO_NUMBER(TRIM(b.ITEM_ID)), TRIM(b.ITEM_NAME), TRIM(b.BRAND_NAME),
       TRY_TO_NUMBER(TRIM(b.SUBCLASS_ID)), TRIM(b.SUBCLASS_NAME),
       TRY_TO_NUMBER(TRIM(b.CATEGORY_ID)), TRIM(b.CATEGORY_NAME), b.BUSINESS_DT
FROM bronze.BRZ_ITEM_MASTER b
WHERE b.BUSINESS_DT = %(business_date)s AND TRY_TO_NUMBER(TRIM(b.ITEM_ID)) IS NOT NULL;