DELETE FROM silver.SLV_INVENTORY_POSITION WHERE BUSINESS_DT = %(business_date)s;

INSERT INTO silver.SLV_INVENTORY_POSITION (SNAPSHOT_DT, STORE_ID, ITEM_ID, ONHAND_QTY, BUSINESS_DT)
SELECT TRY_TO_DATE(TRIM(b.SNAPSHOT_DATE)), TRY_TO_NUMBER(TRIM(b.STORE_ID)),
       TRY_TO_NUMBER(TRIM(b.ITEM_ID)), TRY_TO_NUMBER(TRIM(b.ON_HAND_QTY)), b.BUSINESS_DT
FROM bronze.BRZ_INVENTORY_SNAPSHOT b
WHERE b.BUSINESS_DT = %(business_date)s
  AND TRY_TO_DATE(TRIM(b.SNAPSHOT_DATE)) IS NOT NULL AND TRY_TO_NUMBER(TRIM(b.STORE_ID)) IS NOT NULL
  AND TRY_TO_NUMBER(TRIM(b.ITEM_ID)) IS NOT NULL AND TRY_TO_NUMBER(TRIM(b.ON_HAND_QTY)) IS NOT NULL;