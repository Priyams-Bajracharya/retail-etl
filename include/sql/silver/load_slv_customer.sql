DELETE FROM silver.SLV_CUSTOMER WHERE BUSINESS_DT = %(business_date)s;

INSERT INTO silver.SLV_CUSTOMER (CUSTOMER_ID, CUSTOMER_NM, LOYALTY_FLG, BUSINESS_DT)
SELECT TRY_TO_NUMBER(TRIM(b.CUSTOMER_ID)), TRIM(b.CUSTOMER_NAME),
       UPPER(TRIM(b.LOYALTY_FLAG)) = 'Y', b.BUSINESS_DT
FROM bronze.BRZ_CUSTOMER_MASTER b
WHERE b.BUSINESS_DT = %(business_date)s AND TRY_TO_NUMBER(TRIM(b.CUSTOMER_ID)) IS NOT NULL;