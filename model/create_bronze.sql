USE SCHEMA retail_etl.bronze;

CREATE TABLE IF NOT EXISTS BRZ_ITEM_MASTER (
    ITEM_ID VARCHAR, ITEM_NAME VARCHAR, BRAND_NAME VARCHAR,
    SUBCLASS_ID VARCHAR, SUBCLASS_NAME VARCHAR,
    CATEGORY_ID VARCHAR, CATEGORY_NAME VARCHAR,
    SRC_FILE_NM VARCHAR, SRC_ROW_NUM NUMBER, BUSINESS_DT DATE,
    LOAD_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS BRZ_STORE_MASTER (
    STORE_ID VARCHAR, STORE_NAME VARCHAR,
    DISTRICT_ID VARCHAR, DISTRICT_NAME VARCHAR,
    REGION_ID VARCHAR, REGION_NAME VARCHAR, OPEN_DATE VARCHAR,
    SRC_FILE_NM VARCHAR, SRC_ROW_NUM NUMBER, BUSINESS_DT DATE,
    LOAD_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS BRZ_CUSTOMER_MASTER (
    CUSTOMER_ID VARCHAR, CUSTOMER_NAME VARCHAR, LOYALTY_FLAG VARCHAR,
    SRC_FILE_NM VARCHAR, SRC_ROW_NUM NUMBER, BUSINESS_DT DATE,
    LOAD_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS BRZ_POS_SALES (
    TXN_ID VARCHAR, TXN_LINE_ID VARCHAR, BUSINESS_DATE VARCHAR,
    STORE_ID VARCHAR, CUSTOMER_ID VARCHAR, ITEM_ID VARCHAR,
    QUANTITY VARCHAR, UNIT_PRICE VARCHAR, DISCOUNT_AMOUNT VARCHAR, NET_AMOUNT VARCHAR,
    SRC_FILE_NM VARCHAR, SRC_ROW_NUM NUMBER, BUSINESS_DT DATE,
    LOAD_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS BRZ_INVENTORY_SNAPSHOT (
    SNAPSHOT_DATE VARCHAR, STORE_ID VARCHAR, ITEM_ID VARCHAR, ON_HAND_QTY VARCHAR,
    SRC_FILE_NM VARCHAR, SRC_ROW_NUM NUMBER, BUSINESS_DT DATE,
    LOAD_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

USE SCHEMA retail_etl.bronze;

CREATE FILE FORMAT IF NOT EXISTS CSV_FMT
    TYPE = CSV SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    EMPTY_FIELD_AS_NULL = FALSE NULL_IF = ();

CREATE OR REPLACE STAGE retail_etl.bronze.LANDING_STAGE
    FILE_FORMAT = (FORMAT_NAME = 'RETAIL_ETL.BRONZE.CSV_FMT');
