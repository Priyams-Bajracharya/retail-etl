-- =====================================================================
-- create_tables.sql : Gold layer (Assignment 2.1 model, used by 2.3)
-- 14 tables: 11 dimensions + 3 facts. Safe to run more than once.
-- Snowflake records PK/UK/FK but does not enforce them, so the pipeline
-- checks uniqueness and key lookups itself.
-- =====================================================================
USE SCHEMA retail_etl.gold;

-- ---------------------------------------------------------------------
-- Product hierarchy: DIM_CATG -> DIM_SUBCATG -> DIM_ITEM
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS DIM_CATG (
    CATG_KY       NUMBER AUTOINCREMENT,
    CATG_ID       NUMBER        NOT NULL,
    CATG_NM       VARCHAR(100),
    INSERT_TS     TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATE_TS     TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DIM_CATG PRIMARY KEY (CATG_KY),
    CONSTRAINT UK_DIM_CATG UNIQUE (CATG_ID)
);

CREATE TABLE IF NOT EXISTS DIM_SUBCATG (
    SUBCATG_KY    NUMBER AUTOINCREMENT,
    SUBCATG_ID    NUMBER        NOT NULL,
    SUBCATG_NM    VARCHAR(100),
    CATG_KY       NUMBER        NOT NULL,
    INSERT_TS     TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATE_TS     TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DIM_SUBCATG PRIMARY KEY (SUBCATG_KY),
    CONSTRAINT UK_DIM_SUBCATG UNIQUE (SUBCATG_ID),
    CONSTRAINT FK_SUBCATG_CATG FOREIGN KEY (CATG_KY) REFERENCES DIM_CATG (CATG_KY)
);

-- SCD2 on BRAND_NM and SUBCATG_KY, SCD1 on ITEM_NM.
-- ITEM_ID is NOT unique: one row per version of the item.
CREATE TABLE IF NOT EXISTS DIM_ITEM (
    ITEM_KY       NUMBER AUTOINCREMENT,
    ITEM_ID       NUMBER        NOT NULL,
    ITEM_NM       VARCHAR(200),
    BRAND_NM      VARCHAR(100),
    SUBCATG_KY    NUMBER        NOT NULL,
    CURR_FLG      BOOLEAN       NOT NULL DEFAULT TRUE,
    EFF_START_DT  DATE          NOT NULL,
    EFF_END_DT    DATE          NOT NULL DEFAULT '9999-12-31',
    INSERT_TS     TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATE_TS     TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DIM_ITEM PRIMARY KEY (ITEM_KY),
    CONSTRAINT FK_ITEM_SUBCATG FOREIGN KEY (SUBCATG_KY) REFERENCES DIM_SUBCATG (SUBCATG_KY)
);

-- ---------------------------------------------------------------------
-- Organisation hierarchy: DIM_REGN -> DIM_DISTRICT -> DIM_LOCN
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS DIM_REGN (
    REGN_KY       NUMBER AUTOINCREMENT,
    REGN_ID       NUMBER        NOT NULL,
    REGN_NM       VARCHAR(100),
    COUNTRY_NM    VARCHAR(100),
    INSERT_TS     TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATE_TS     TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DIM_REGN PRIMARY KEY (REGN_KY),
    CONSTRAINT UK_DIM_REGN UNIQUE (REGN_ID)
);

CREATE TABLE IF NOT EXISTS DIM_DISTRICT (
    DISTRICT_KY   NUMBER AUTOINCREMENT,
    DISTRICT_ID   NUMBER        NOT NULL,
    DISTRICT_NM   VARCHAR(100),
    REGN_KY       NUMBER        NOT NULL,
    INSERT_TS     TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATE_TS     TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DIM_DISTRICT PRIMARY KEY (DISTRICT_KY),
    CONSTRAINT UK_DIM_DISTRICT UNIQUE (DISTRICT_ID),
    CONSTRAINT FK_DISTRICT_REGN FOREIGN KEY (REGN_KY) REFERENCES DIM_REGN (REGN_KY)
);

-- SCD2 on DISTRICT_KY, SCD1 on LOCN_NM.
-- LOCN_ID is NOT unique: one row per version of the store.
CREATE TABLE IF NOT EXISTS DIM_LOCN (
    LOCN_KY       NUMBER AUTOINCREMENT,
    LOCN_ID       NUMBER        NOT NULL,
    LOCN_NM       VARCHAR(200),
    DISTRICT_KY   NUMBER        NOT NULL,
    CURR_FLG      BOOLEAN       NOT NULL DEFAULT TRUE,
    EFF_START_DT  DATE          NOT NULL,
    EFF_END_DT    DATE          NOT NULL DEFAULT '9999-12-31',
    INSERT_TS     TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATE_TS     TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DIM_LOCN PRIMARY KEY (LOCN_KY),
    CONSTRAINT FK_LOCN_DISTRICT FOREIGN KEY (DISTRICT_KY) REFERENCES DIM_DISTRICT (DISTRICT_KY)
);

-- ---------------------------------------------------------------------
-- Calendar: DIM_YEAR -> DIM_MONTH / DIM_WEEK -> DIM_DAY
-- Keys here are NOT auto-numbered: the seed task supplies them
-- (for example DAY_KY = 20261111).
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS DIM_YEAR (
    YEAR_KY        NUMBER       NOT NULL,
    YEAR_ID        NUMBER       NOT NULL,
    YEAR_START_DT  DATE         NOT NULL,
    YEAR_END_DT    DATE         NOT NULL,
    INSERT_TS      TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATE_TS      TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DIM_YEAR PRIMARY KEY (YEAR_KY),
    CONSTRAINT UK_DIM_YEAR UNIQUE (YEAR_ID)
);

CREATE TABLE IF NOT EXISTS DIM_MONTH (
    MONTH_KY        NUMBER       NOT NULL,
    MONTH_ID        NUMBER       NOT NULL,
    MONTH_NUM       NUMBER       NOT NULL,
    MONTH_NM        VARCHAR(20)  NOT NULL,
    MONTH_START_DT  DATE         NOT NULL,
    MONTH_END_DT    DATE         NOT NULL,
    YEAR_KY         NUMBER       NOT NULL,
    INSERT_TS       TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATE_TS       TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DIM_MONTH PRIMARY KEY (MONTH_KY),
    CONSTRAINT UK_DIM_MONTH UNIQUE (MONTH_ID),
    CONSTRAINT FK_MONTH_YEAR FOREIGN KEY (YEAR_KY) REFERENCES DIM_YEAR (YEAR_KY)
);

CREATE TABLE IF NOT EXISTS DIM_WEEK (
    WEEK_KY        NUMBER       NOT NULL,
    WEEK_ID        NUMBER       NOT NULL,
    WEEK_NUM       NUMBER       NOT NULL,
    WEEK_START_DT  DATE         NOT NULL,
    WEEK_END_DT    DATE         NOT NULL,
    YEAR_KY        NUMBER       NOT NULL,
    INSERT_TS      TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATE_TS      TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DIM_WEEK PRIMARY KEY (WEEK_KY),
    CONSTRAINT UK_DIM_WEEK UNIQUE (WEEK_ID),
    CONSTRAINT FK_WEEK_YEAR FOREIGN KEY (YEAR_KY) REFERENCES DIM_YEAR (YEAR_KY)
);

CREATE TABLE IF NOT EXISTS DIM_DAY (
    DAY_KY      NUMBER       NOT NULL,
    DAY_ID      NUMBER       NOT NULL,
    FULL_DT     DATE         NOT NULL,
    DAY_NUM     NUMBER       NOT NULL,
    WEEK_KY     NUMBER       NOT NULL,
    MONTH_KY    NUMBER       NOT NULL,
    INSERT_TS   TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATE_TS   TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DIM_DAY PRIMARY KEY (DAY_KY),
    CONSTRAINT UK_DIM_DAY UNIQUE (DAY_ID),
    CONSTRAINT FK_DAY_WEEK FOREIGN KEY (WEEK_KY) REFERENCES DIM_WEEK (WEEK_KY),
    CONSTRAINT FK_DAY_MONTH FOREIGN KEY (MONTH_KY) REFERENCES DIM_MONTH (MONTH_KY)
);

-- ---------------------------------------------------------------------
-- Customer: only the Unknown row (-1) is loaded, the files have no customers
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS DIM_CUSTOMER (
    CUSTOMER_KY   NUMBER       NOT NULL,
    CUSTOMER_ID   NUMBER       NOT NULL,
    CUSTOMER_NM   VARCHAR(200),
    LOYALTY_FLG   BOOLEAN,
    INSERT_TS     TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATE_TS     TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DIM_CUSTOMER PRIMARY KEY (CUSTOMER_KY),
    CONSTRAINT UK_DIM_CUSTOMER UNIQUE (CUSTOMER_ID)
);

-- ---------------------------------------------------------------------
-- Facts
-- ---------------------------------------------------------------------
-- Grain: one row per sales transaction line (TXN_ID + TXN_LINE_ID).
-- SLS_AMT = net amount (quantity x price - discount). DISC_AMT is the
-- discount, added to the 2.1 model because pos_sales carries it.
CREATE TABLE IF NOT EXISTS FCT_SALES (
    SLS_LINE_KY      NUMBER AUTOINCREMENT,
    TXN_ID           VARCHAR(50)   NOT NULL,
    TXN_LINE_ID      NUMBER        NOT NULL,
    ITEM_KY          NUMBER        NOT NULL,
    LOCN_KY          NUMBER        NOT NULL,
    DAY_KY           NUMBER        NOT NULL,
    CUSTOMER_KY      NUMBER        NOT NULL,
    SLS_QTY          NUMBER        NOT NULL,
    UNIT_PRICE_AMT   NUMBER(12,2)  NOT NULL,
    DISC_AMT         NUMBER(12,2)  NOT NULL DEFAULT 0,
    SLS_AMT          NUMBER(14,2)  NOT NULL,
    INSERT_TS        TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATE_TS        TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_FCT_SALES PRIMARY KEY (SLS_LINE_KY),
    CONSTRAINT UK_FCT_SALES UNIQUE (TXN_ID, TXN_LINE_ID),
    CONSTRAINT FK_SALES_ITEM FOREIGN KEY (ITEM_KY) REFERENCES DIM_ITEM (ITEM_KY),
    CONSTRAINT FK_SALES_LOCN FOREIGN KEY (LOCN_KY) REFERENCES DIM_LOCN (LOCN_KY),
    CONSTRAINT FK_SALES_DAY FOREIGN KEY (DAY_KY) REFERENCES DIM_DAY (DAY_KY),
    CONSTRAINT FK_SALES_CUSTOMER FOREIGN KEY (CUSTOMER_KY) REFERENCES DIM_CUSTOMER (CUSTOMER_KY)
);

-- Positional: one row per item and location for each period with the same
-- on-hand quantity. Rows are closed (EFF_END_DT set), never deleted.
-- INV_VALUE_AMT stays empty: the inventory file has no value column.
CREATE TABLE IF NOT EXISTS FCT_INVENTORY (
    INV_KY          NUMBER AUTOINCREMENT,
    ITEM_KY         NUMBER        NOT NULL,
    LOCN_KY         NUMBER        NOT NULL,
    EFF_START_DT    DATE          NOT NULL,
    EFF_END_DT      DATE          NOT NULL DEFAULT '9999-12-31',
    ONHAND_QTY      NUMBER        NOT NULL,
    INV_VALUE_AMT   NUMBER(14,2),
    INSERT_TS       TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATE_TS       TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_FCT_INVENTORY PRIMARY KEY (INV_KY),
    CONSTRAINT FK_INV_ITEM FOREIGN KEY (ITEM_KY) REFERENCES DIM_ITEM (ITEM_KY),
    CONSTRAINT FK_INV_LOCN FOREIGN KEY (LOCN_KY) REFERENCES DIM_LOCN (LOCN_KY)
);

-- Created for the model but not loaded in 2.3: no file supplies prices.
CREATE TABLE IF NOT EXISTS FCT_PRICE (
    PRICE_KY        NUMBER AUTOINCREMENT,
    ITEM_KY         NUMBER        NOT NULL,
    LOCN_KY         NUMBER        NOT NULL,
    DAY_KY          NUMBER        NOT NULL,
    PRICE_AMT       NUMBER(12,2)  NOT NULL,
    EFF_START_DT    DATE          NOT NULL,
    EFF_END_DT      DATE          NOT NULL DEFAULT '9999-12-31',
    INSERT_TS       TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATE_TS       TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_FCT_PRICE PRIMARY KEY (PRICE_KY),
    CONSTRAINT FK_PRICE_ITEM FOREIGN KEY (ITEM_KY) REFERENCES DIM_ITEM (ITEM_KY),
    CONSTRAINT FK_PRICE_LOCN FOREIGN KEY (LOCN_KY) REFERENCES DIM_LOCN (LOCN_KY),
    CONSTRAINT FK_PRICE_DAY FOREIGN KEY (DAY_KY) REFERENCES DIM_DAY (DAY_KY)
);
