USE SCHEMA retail_etl.silver;

CREATE TABLE IF NOT EXISTS SLV_ITEM (
    ITEM_ID NUMBER NOT NULL, ITEM_NM VARCHAR(200), BRAND_NM VARCHAR(100),
    SUBCLASS_ID NUMBER, SUBCLASS_NM VARCHAR(100),
    CATEGORY_ID NUMBER, CATEGORY_NM VARCHAR(100),
    BUSINESS_DT DATE NOT NULL,
    LOAD_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS SLV_LOCATION (
    STORE_ID NUMBER NOT NULL, STORE_NM VARCHAR(200),
    DISTRICT_ID NUMBER, DISTRICT_NM VARCHAR(100),
    REGION_ID NUMBER, REGION_NM VARCHAR(100), OPEN_DT DATE,
    BUSINESS_DT DATE NOT NULL,
    LOAD_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS SLV_CUSTOMER (
    CUSTOMER_ID NUMBER NOT NULL, CUSTOMER_NM VARCHAR(200), LOYALTY_FLG BOOLEAN,
    BUSINESS_DT DATE NOT NULL,
    LOAD_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS SLV_SALES_LINE (
    TXN_ID VARCHAR(50) NOT NULL, TXN_LINE_ID NUMBER NOT NULL,
    SALE_DT DATE NOT NULL, STORE_ID NUMBER NOT NULL,
    CUSTOMER_ID NUMBER,                -- empty = anonymous sale
    ITEM_ID NUMBER NOT NULL, SLS_QTY NUMBER NOT NULL,
    UNIT_PRICE_AMT NUMBER(12,2) NOT NULL, DISC_AMT NUMBER(12,2) NOT NULL,
    SLS_AMT NUMBER(14,2) NOT NULL,
    SRC_ROW_NUM NUMBER, BUSINESS_DT DATE NOT NULL,
    LOAD_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS SLV_INVENTORY_POSITION (
    SNAPSHOT_DT DATE NOT NULL, STORE_ID NUMBER NOT NULL, ITEM_ID NUMBER NOT NULL,
    ONHAND_QTY NUMBER NOT NULL, BUSINESS_DT DATE NOT NULL,
    LOAD_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Quarantine: every rejected row, with a reason code.
-- REASON_CD values: NULL_ITEM_ID, NEGATIVE_QTY, ITEM_NOT_IN_MASTER, DUPLICATE_LINE
CREATE TABLE IF NOT EXISTS REJ_ROW (
    REJ_KY NUMBER AUTOINCREMENT,
    BUSINESS_DT DATE NOT NULL,
    SRC_TABLE VARCHAR(50) NOT NULL,
    SRC_FILE_NM VARCHAR(200),
    SRC_ROW_NUM NUMBER,
    REASON_CD VARCHAR(50) NOT NULL,
    REASON_TXT VARCHAR(500),
    ROW_DATA VARCHAR,                   -- the original row, as text
    REJ_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
